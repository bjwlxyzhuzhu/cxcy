export const CREW_BY_KEY: Record<string, CrewRole> = Object.fromEntries(CREW.map((c) => [c.key, c]));

/** 把项目记忆拼成给搭子的上下文（注入 system）。 */
export function projectContext(p: Project): string {
  const filled = BP_SECTIONS.filter((s) => (p.sections[s.key] || "").trim());
  const head = `项目名：${p.name || "（未命名）"}；学生专业：${p.major || "未选"}。`;
  if (!filled.length && !p.draft) {
    return head + " 项目刚起步、各部分还空着——请引导用户从「痛点与需求」「解决方案」开始沉淀。";
  }
  const body = filled.map((s) => `【${s.label}】${p.sections[s.key]}`).join("\n");
  return head + "\n已沉淀的项目记忆：\n" + (body || "（暂无分节）") + (p.draft ? "\n（已生成 BP 草案）" : "");
}

